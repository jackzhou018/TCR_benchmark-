#!/usr/bin/env python
"""Write a ready-to-run PyMOL script and ChimeraX script into each case folder.

    python RMSD_diff/figure_cases/make_views.py
    pymol RMSD_diff/figure_cases/8RYO/8RYO.pml
    chimerax RMSD_diff/figure_cases/8RYO/8RYO.cxc

The camera comes from each native's own geometry -- screen up = MHC centre -> native TCR
centre, screen right = peptide N->C perpendicular to it -- so the native TCR is straight up and
the peptide horizontal in all four panels, and a prediction that docks elsewhere is off-axis by
construction. (The alpha1alpha2 slab is too thick for its own thin PCA axis to be a reliable
groove normal, and the MHC->peptide vector is up to 45 deg off; the native TCR is the reference
the figure is about anyway.)

Three scenes per case:
  side       whole complex, groove horizontal, native TCR up
  top        same camera turned onto the platform normal
  footprint  top, TCR bodies hidden, one sphere per variable domain -- an in-plane flip is
             invisible in `side` and occluded by the TCR in `top`, and this is what shows it
"""
import os
import gemmi, numpy as np

D = os.path.dirname(os.path.abspath(__file__))
CASES = ["8RYO", "9NW2", "9RU5", "9GV7",          # divergent
         "8RYP", "43RH", "8QFY", "8WUL", "8PJG"]  # both models right
MODELS = [("native", "gray70"), ("AF3", "firebrick"), ("ESM", "teal")]


def ca(st, chain):
    return np.array([[a.pos.x, a.pos.y, a.pos.z] for r in st[0][chain]
                     if (a := r.find_atom("CA", "*"))])


def view(axes, origin, dist=250):
    # set_view's rotation is column-major -- the transpose of camera-axes-as-rows
    m = ",".join(f"{axes[j][i]:.4f}" for i in range(3) for j in range(3))
    o = ",".join(f"{v:.4f}" for v in origin)
    return (f"set_view (\\\n  {m},\\\n  0.0,0.0,{-dist:.1f},\\\n  {o},\\\n"
            f"  {dist - 150:.1f},{dist + 150:.1f},-20.0 )")


for p in CASES:
    files = {t: f"{p}_{'ESMFold2' if t == 'ESM' else t}.cif" for t, _ in MODELS}
    st = gemmi.read_structure(f"{D}/{p}/{files['native']}"); st.setup_entities()
    names = [c.name for c in st[0]]
    va, vb = ("D", "E") if "E" in names else ("C", "D")
    A, B = ca(st, "A"), ca(st, "B")
    up = np.vstack([ca(st, va), ca(st, vb)]).mean(0) - A.mean(0); up /= np.linalg.norm(up)
    right = B[-1] - B[0]; right -= right @ up * up; right /= np.linalg.norm(right)
    fwd = np.cross(right, up)
    o = np.vstack([A, B]).mean(0)

    marks = []
    for tag, col in MODELS:
        s2 = gemmi.read_structure(f"{D}/{p}/{files[tag]}"); s2.setup_entities()
        for ch, lab in ((va, "Va"), (vb, "Vb")):
            x, y, z = ca(s2, ch).mean(0)
            marks += [f"pseudoatom {tag}_{lab}, pos=[{x:.2f},{y:.2f},{z:.2f}], color={col}",
                      f"show spheres, {tag}_{lab}",
                      f"set sphere_scale, {4.0 if lab == 'Va' else 2.4}, {tag}_{lab}"]
    marks.append("set sphere_transparency, 0.1, *_V*")

    # ChimeraX: `view matrix camera` takes the camera's 3x4 position matrix, columns = camera
    # axes in scene coords + camera centre. Not verified by rendering -- no ChimeraX here.
    cam = np.column_stack([right, up, fwd, o + fwd * 220])
    open(f"{D}/{p}/{p}.cxc", "w").write(f"""# {p} -- generated by ../make_views.py
open {files['native']} {files['AF3']} {files['ESM']}
hide atoms; show cartoon
color #1 gray; color #2 firebrick; color #3 teal
transparency #1 55 cartoons
show /B & ~hydrogen atoms
style /B stick
set bgColor white
lighting soft; graphics silhouettes false
# groove horizontal, native TCR up (same camera as the PyMOL `side` scene)
view matrix camera {','.join(f'{v:.4f}' for v in cam.flatten())}
""")

    open(f"{D}/{p}/{p}.pml", "w").write(f"""# {p} -- generated by ../make_views.py
# Va = big sphere, Vb = small sphere. chains: A MHC, B peptide, {va} TCRa, {vb} TCRb.
load {files['native']}, native
load {files['AF3']}, AF3
load {files['ESM']}, ESM

bg_color white
hide everything
show cartoon
set cartoon_transparency, 0.55, native
color gray70, native
color firebrick, AF3
color teal, ESM
show sticks, chain B and not hydro
set cartoon_side_chain_helper, 1
set ray_shadows, 0
set antialias, 2
set orthoscopic, 1

{chr(10).join(marks)}
disable *_V*

# whole complex, groove horizontal, native TCR up
{view([right, up, fwd], o)}
zoom native or AF3 or ESM, 4
scene side, store

# same camera rotated onto the platform normal, viewed from the TCR side
{view([right, -fwd, up], o)}
zoom native or AF3 or ESM, 4
scene top, store

# footprint: TCR bodies off, variable-domain centroids on
hide cartoon, chain {va}+{vb}
enable *_V*
zoom chain A or chain B or *_V*, 4
scene footprint, store
show cartoon, chain {va}+{vb}
disable *_V*

scene side, recall
""")
    print(f"{D}/{p}/{p}.pml")
